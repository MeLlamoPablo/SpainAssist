// The channel's test vectors live with the TypeScript implementation (packages/companion): the
// common tests read them from a generated source file, so both sides check the same bytes.
val vectorsJson = rootProject.layout.projectDirectory.file("../../packages/companion/vectors/v1.json")
val generatedTestSources = layout.buildDirectory.dir("generated/vectors/kotlin")
val generateVectors = tasks.register("generateVectors") {
    inputs.file(vectorsJson)
    outputs.dir(generatedTestSources)
    val source = vectorsJson.asFile
    val target = generatedTestSources.get().file("es/spainassist/firma/Vectors.kt").asFile
    doLast {
        // JVM string constants stop at 64 KB: join chunks at run time.
        val chunks = source.readText().chunked(20_000).joinToString(",\n") { chunk ->
            "    \"" + chunk.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
                .replace("$", "\\$") + "\""
        }
        target.parentFile.mkdirs()
        target.writeText(
            "package es.spainassist.firma\n\n" +
                "/** packages/companion/vectors/v1.json, generated by shared/build.gradle.kts. */\n" +
                "internal val VECTORS_JSON: String = listOf(\n$chunks,\n).joinToString(\"\")\n",
        )
    }
}

