/** The decrypted contents of vault.bin and its (de)serialization. */
import { CertificateInfo, CredentialPolicy, DocumentMeta, PersonalDataSource } from '@sa/shared';
import { z } from 'zod';
import { VaultError } from './errors';

export interface PersonalEntry {
  value: string;
  source: PersonalDataSource;
  updatedAt: string;
  /** Custom keys only (well-known keys take their label from PERSONAL_FIELDS). */
  label?: string;
}

interface CredentialBase {
  id: string;
  label: string;
  policy: CredentialPolicy;
  createdAt: string;
  lastUsedAt?: string;
}

export interface StoredClave extends CredentialBase {
  kind: 'clave_permanente';
  username: string;
  password: string;
}

export interface StoredClaveMovil extends CredentialBase {
  kind: 'clave_movil';
}

export interface StoredCertificate extends CredentialBase {
  kind: 'certificate';
  fileName: string;
  /** Normalized PKCS#12 (base64). */
  p12: string;
  /** Passphrase of the normalized PKCS#12 (generated by the vault). */
  passphrase: string;
  /** e.g. "rsa 2048", "ec prime256v1". */
  keyDescription: string;
  certificate: CertificateInfo;
}

/**
 * The DNIe signs in the paired phone; we keep its certificate's details once read, and its PIN
 * once the user saves it or the card accepts a typed one (D22).
 */
export interface StoredDnie extends CredentialBase {
  kind: 'dnie';
  certificate?: CertificateInfo;
  pin?: string;
}

export type StoredCredential = StoredClave | StoredClaveMovil | StoredCertificate | StoredDnie;

export interface StoredSecret {
  label: string;
  value: string;
  createdAt: string;
  updatedAt: string;
}

/** In memory, keyed collections are Maps (no prototype pitfalls with user-chosen keys). */
export interface VaultState {
  createdAt: string;
  personal: Map<string, PersonalEntry>;
  documents: Map<string, DocumentMeta>;
  credentials: StoredCredential[];
  secrets: Map<string, StoredSecret>;
}

const credentialBase = {
  id: z.string(),
  label: z.string(),
  policy: CredentialPolicy,
  createdAt: z.string(),
  lastUsedAt: z.string().optional(),
};

const StateFile = z.object({
  version: z.literal(1),
  createdAt: z.string(),
  personal: z.record(
    z.string(),
    z.object({
      value: z.string(),
      source: PersonalDataSource,
      updatedAt: z.string(),
      label: z.string().optional(),
    }),
  ),
  documents: z.record(z.string(), DocumentMeta),
  credentials: z.array(
    z.discriminatedUnion('kind', [
      z.object({
        ...credentialBase,
        kind: z.literal('clave_permanente'),
        username: z.string(),
        password: z.string(),
      }),
      z.object({ ...credentialBase, kind: z.literal('clave_movil') }),
      z.object({
        ...credentialBase,
        kind: z.literal('certificate'),
        fileName: z.string(),
        p12: z.string(),
        passphrase: z.string(),
        keyDescription: z.string(),
        certificate: CertificateInfo,
      }),
      z.object({
        ...credentialBase,
        kind: z.literal('dnie'),
        certificate: CertificateInfo.optional(),
        pin: z.string().optional(),
      }),
    ]),
  ),
  secrets: z.record(
    z.string(),
    z.object({
      label: z.string(),
      value: z.string(),
      createdAt: z.string(),
      updatedAt: z.string(),
    }),
  ),
});

export function emptyState(now: string): VaultState {
  return {
    createdAt: now,
    personal: new Map(),
    documents: new Map(),
    credentials: [],
    secrets: new Map(),
  };
}

export function cloneState(state: VaultState): VaultState {
  return {
    createdAt: state.createdAt,
    personal: new Map(state.personal),
    documents: new Map(state.documents),
    credentials: [...state.credentials],
    secrets: new Map(state.secrets),
  };
}

export function serializeState(state: VaultState): Buffer {
  return Buffer.from(
    JSON.stringify({
      version: 1,
      createdAt: state.createdAt,
      personal: Object.fromEntries(state.personal),
      documents: Object.fromEntries(state.documents),
      credentials: state.credentials,
      secrets: Object.fromEntries(state.secrets),
    }),
    'utf8',
  );
}

export function parseState(json: Buffer): VaultState {
  let data: z.infer<typeof StateFile>;
  try {
    data = StateFile.parse(JSON.parse(json.toString('utf8')));
  } catch (e) {
    throw new VaultError('corrupted', 'The vault contents are not valid', { cause: e });
  }
  return {
    createdAt: data.createdAt,
    personal: new Map(Object.entries(data.personal)),
    documents: new Map(Object.entries(data.documents)),
    credentials: data.credentials,
    secrets: new Map(Object.entries(data.secrets)),
  };
}
