import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';

const directory = new URL('../apps/desktop/src/renderer/src/design/', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('color-tokens.json', directory), 'utf8'));
for (const field of ['key', 'name', 'framerId']) {
  assert.equal(
    new Set(tokens.map((token) => token[field])).size,
    tokens.length,
    `Duplicate ${field}`,
  );
}
for (const token of tokens) {
  assert.match(token.key, /^--(?:sa|st)-[a-z0-9-]+$/);
  assert.match(token.framerId, /^[a-f0-9-]{36}$/);
  for (const mode of ['light', 'dark']) {
    assert.match(token[mode], /^rgba\(\d+, \d+, \d+, (?:0|1|0\.\d+)\)$/);
    const [r, g, b, alpha] = token[mode].match(/[\d.]+/g).map(Number);
    assert.ok([r, g, b].every((value) => value >= 0 && value <= 255));
    assert.ok(alpha >= 0 && alpha <= 1);
  }
}
const declarations = (mode, indent) =>
  tokens.map((token) => `${indent}${token.key}: ${token[mode]};`).join('\n');
const css = `/* Generated by tools/design-colors.mjs from color-tokens.json. */
:root {
${declarations('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${declarations('dark', '    ')}
  }
}
`;
const file = new URL('colors.css', directory);
if (process.argv.includes('--check')) {
  assert.equal(
    await readFile(file, 'utf8'),
    css,
    'Run node tools/design-colors.mjs to regenerate colors.css',
  );
  console.log(`${tokens.length} color tokens: generated CSS is in sync.`);
} else {
  await writeFile(file, css);
  console.log(`Generated ${tokens.length} color tokens.`);
}

// A Framer export is optional: this maintenance tool never accesses the network.
const exportIndex = process.argv.indexOf('--framer-styles');
if (exportIndex !== -1) {
  const styles = JSON.parse(await readFile(process.argv[exportIndex + 1], 'utf8'));
  const normalize = (color) => {
    const values = color.match(/[\d.]+/g).map(Number);
    return [...values.slice(0, 3), values[3] ?? 1];
  };
  for (const token of tokens) {
    const style = styles.find((item) => item.id === token.framerId);
    assert.ok(style, `Missing Framer style: ${token.name}`);
    assert.equal(style.path, `/${token.name}`);
    for (const mode of ['light', 'dark']) {
      assert.deepEqual(
        normalize(style[mode]),
        normalize(token[mode]),
        `${token.name}: ${mode} differs`,
      );
    }
  }
  console.log(`${tokens.length} Framer styles match the canonical light and dark palette.`);
}
